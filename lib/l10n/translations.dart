String translateFor(String language, String source) {
  if (language != 'en') return englishToVietnamese[source] ?? source;
  final exact = vietnameseToEnglish[source];
  if (exact != null) return exact;
  for (final entry in _patterns) {
    final match = entry.$1.firstMatch(source);
    if (match != null) return entry.$2(match);
  }
  return source;
}

final _patterns = <(RegExp, String Function(RegExpMatch))>[
  (
    RegExp(r'^Bạn chắc chắn muốn xóa hồ sơ của (.+)\?$'),
    (m) => 'Delete the profile for ${m[1]}?'
  ),
  (
    RegExp(r'^Đã cập nhật cân nặng cho (.+)$'),
    (m) => 'Weight updated for ${m[1]}'
  ),
  (
    RegExp(r'^Chuyển (.+) từ (.+) thành (.+)\?$'),
    (m) =>
        'Change ${m[1]} from ${translateFor('en', m[2]!)} to ${translateFor('en', m[3]!)}?'
  ),
  (
    RegExp(r'^Đặt lịch khám cho (.+)$'),
    (m) => 'Book an appointment for ${m[1]}'
  ),
  (RegExp(r'^Đặt lịch cho (.+)$'), (m) => 'Book for ${m[1]}'),
  (RegExp(r'^(.+) - (\d+) tuổi$'), (m) => '${m[1]} - ${m[2]} years old'),
  (RegExp(r'^(\d+) tuổi$'), (m) => '${m[1]} years old'),
  (RegExp(r'^Còn (\d+) mũi$'), (m) => '${m[1]} doses remaining'),
  (RegExp(r'^Còn (\d+) ngày$'), (m) => 'In ${m[1]} days'),
  (RegExp(r'^Đã tiêm (.+)$'), (m) => 'Vaccinated on ${m[1]}'),
  (RegExp(r'^Dự kiến (.+)$'), (m) => 'Scheduled for ${m[1]}'),
  (RegExp(r'^Nhắc lại: (.+)$'), (m) => 'Booster: ${m[1]}'),
